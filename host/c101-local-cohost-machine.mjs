// C101 is a composition of EXISTING bounded owners: no new state, runtime
// authority, retry system, user-event attestation or ChatGPT host hook.
const SCHEMA='ikant-le-c101-local-cohost-machine/v1';
const H40=/^[0-9a-f]{40}$/;
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
const gitBlob=b=>crypto.createHash('sha1').update(Buffer.concat([
 Buffer.from(`blob ${b.length}\0`),b])).digest('hex');
const denial=Object.freeze({authority:0,active:false,canonical_runtime:false,
 persistent:false,source_origin_attested:false,native_event_attested:false,
 native_delivery_attested:false,c84_owner_executed:false,
 owner_receipt_issued:false,inter_turn_continuity_attested:false});
const stop=(edge)=>Object.freeze({schema:SCHEMA,status:'C101_STOP',
 first_unclosed_edge:edge,...denial});
function exactData(x,keys){
 try{
  if(!x||typeof x!=='object'||Array.isArray(x)||isProxy(x)||
      Object.getPrototypeOf(x)!==Object.prototype)return null;
  const names=Reflect.ownKeys(x);
  if(names.some(k=>typeof k!=='string'||!keys.includes(k)))return null;
  const out={};
  for(const k of keys){
   const d=Object.getOwnPropertyDescriptor(x,k);
   if(d&&!Object.hasOwn(d,'value'))return null;
   out[k]=d?.value;
  }
  return out;
 }catch{return null;}
}
function safeSelection(x){
 try{
  if(!x||typeof x!=='object'||Array.isArray(x)||isProxy(x)||
    Object.getPrototypeOf(x)!==Object.prototype)return false;
  return Reflect.ownKeys(x).every(k=>typeof k==='string'&&
    Object.hasOwn(Object.getOwnPropertyDescriptor(x,k),'value'));
 }catch{return false;}
}
/**
 * sourceHead: FROZEN HOST ASSERTION, never a new GitHub origin proof.
 * optIn: host-observed preference, not a native-event identity.
 * modelCandidate: optional host LLM text, not generated by this module.
 * Same-input voice is EXACTLY C71's local readback, with a C100 binder.
 */
export function executeC101LocalCohostMachine(input={}){
 const f=exactData(input,['sourceHead','selection','humanInput','optIn','modelCandidate']);
 if(!f)return stop('C101_INPUT_DATA_DESCRIPTOR_REQUIRED');
 const {sourceHead,selection,humanInput,optIn,modelCandidate}=f;
 if(!H40.test(sourceHead||'')||!safeSelection(selection)||
    !validateC72ModeSelection(selection,{mode:'EXPERIMENTAL',sourceHead}))
  return stop('REAL_C72_EXPERIMENTAL_SOURCE_BOUND_SELECTION_REQUIRED');
 if(optIn!==true)return stop('SEPARATE_C100_COHOST_OPT_IN_REQUIRED');
 if(typeof humanInput!=='string'||!humanInput.trim()||
    Buffer.byteLength(humanInput,'utf8')>600||
    Buffer.from(humanInput,'utf8').toString('utf8')!==humanInput)
  return stop('BOUNDED_CURRENT_HUMAN_INPUT_REQUIRED');
 if(modelCandidate!==undefined&&(typeof modelCandidate!=='string'||
    !modelCandidate.trim()||Buffer.byteLength(modelCandidate,'utf8')>3500||
    Buffer.from(modelCandidate,'utf8').toString('utf8')!==modelCandidate))
  return stop('BOUNDED_HOST_MODEL_CANDIDATE_REQUIRED');
 // C100 is checked BEFORE local source IO: no secrets/overridden consent.
 const plan=prepareC100CohostDraft({sourceHead,selection,humanInput,optIn:true});
 if(plan.status!=='C100_COHOST_PLAN_READY_UNATTESTED')
  return stop(plan.first_unclosed_edge||'C100_PREPARE_REFUSED');
 try{
  // Exactly the local installed repository README; self-identity check ONLY.
  // This is NOT proof that GitHub main refers to these executable modules.
  const readme=fs.readFileSync(new URL('../README.md',import.meta.url));
  const envelope={sourceHead,unifiedSelection:selection,
   offer:issueC69ExperimentalOffer({sourceHead}),
   sourceObject:{path:'README.md',blob_sha1:gitBlob(readme),
      content_base64:readme.toString('base64')},messages:[humanInput]};
  if(modelCandidate!==undefined)envelope.drafts=[{
    input_sha256:sha(Buffer.from(humanInput,'utf8')),text:modelCandidate}];
  const c71=routeC71HostDraft(envelope); // This actually invokes C70.
  if(c71.status!=='EXPERIMENTAL_HOST_DRAFT'||
     c71.executed_repository_kernel!==true||
     c71.routed_turns?.length!==1)return stop(c71.first_unclosed_edge||'C70_C71_READBACK');
  const turn=c71.routed_turns[0],voice=turn.text;
  if(typeof voice!=='string'||turn.input_sha256!==plan.input_sha256||
     turn.output_sha256!==sha(Buffer.from(voice,'utf8'))||
     turn.node_dispatch_input_bound!==true||turn.action_executed!==false)
    return stop('C101_C71_SAME_INPUT_OUTPUT_INTEGRITY');
  const bound=finalizeC100CohostDraft({plan,planSha256:plan.plan_sha256,
    modelText:voice});
  if(bound.status!=='C100_MODEL_DRAFT_UNATTESTED_NOT_OWNER'||
    bound.bound_input_sha256!==turn.input_sha256||
    bound.bound_output_sha256!==turn.output_sha256||bound.active!==false)
    return stop(bound.first_unclosed_edge||'C101_C100_OUTPUT_BINDING');
  return Object.freeze({schema:SCHEMA,
   status:'C101_LOCAL_MACHINE_VOICE_READY_NOT_NATIVE_DELIVERED',
   mode:'EXPERIMENTAL',source_head:sourceHead,
   input_sha256:turn.input_sha256,output_sha256:turn.output_sha256,
   plan_sha256:bound.plan_sha256,voice_utf8:voice,
   voice_source:turn.source,method:turn.method,
   central_mode:turn.central_mode,guarded:turn.guarded,
   host_candidate_used:turn.host_candidate_used,
   cognitive_kernel_executed:true,local_machine_executed:true,
   c70_status:c71.c70_status,c71_status:c71.status,c100_status:bound.status,
   local_readme_blob_sha1:gitBlob(readme),
   evidence_scope:'LOCAL_C70_C71_C100_EXECUTION_NOT_C84_OR_GITHUB_ORIGIN',
   first_unclosed_edge:'HOST_NATIVE_AUTOMATIC_DISPATCH_AND_DELIVERY_NOT_ATTESTED',
   ...denial});
 }catch{return stop('C101_LOCAL_MODULE_OR_README_EXECUTION_UNAVAILABLE');}
}

export function verifyC101Readback(r,input){
 try{
  const i=exactData(input,['sourceHead','selection','humanInput','optIn','modelCandidate']);
  if(!i||!r||isProxy(r)||r.schema!==SCHEMA||
    r.status!=='C101_LOCAL_MACHINE_VOICE_READY_NOT_NATIVE_DELIVERED'||
    r.source_head!==i.sourceHead||r.active!==false||r.c84_owner_executed!==false||
    r.native_delivery_attested!==false||r.persistent!==false||
    r.cognitive_kernel_executed!==true||r.local_machine_executed!==true||
    r.input_sha256!==sha(Buffer.from(i.humanInput,'utf8'))||
    typeof r.voice_utf8!=='string'||
    r.output_sha256!==sha(Buffer.from(r.voice_utf8,'utf8')))
   return Object.freeze({ok:false,first_unclosed_edge:'C101_READBACK_INTEGRITY'});
  return Object.freeze({ok:true,first_unclosed_edge:r.first_unclosed_edge});
 }catch{return Object.freeze({ok:false,first_unclosed_edge:'C101_READBACK_INTEGRITY'});}
}